// Regenerates VERSION and ASSETS in sw.js from the shipped runtime files.
// Usage: node tools/stamp-sw.mjs [--check]   (--check: exit 1 if sw.js is stale, write nothing)
//
// Shipped files: index.html, manifest.webmanifest, css/*.css, js/**/*.js, icons/* (dotfiles skipped).
// Never tests/, tools/, docs/, package.json or sw.js itself.
// VERSION = first 8 hex chars of SHA-256 over the asset paths sorted by code unit, each fed as
//   path + '\0' + file bytes + '\0'.
import { createHash } from 'node:crypto'
import { readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)))

const TOP_FILES = ['index.html', 'manifest.webmanifest']

async function walk(root, dir, { recursive, ext }) {
  let entries
  try {
    entries = await readdir(join(root, dir), { withFileTypes: true })
  } catch {
    return []
  }
  const out = []
  for (const e of entries) {
    if (e.name.startsWith('.')) continue
    const rel = dir + '/' + e.name
    if (e.isDirectory()) {
      if (recursive) out.push(...await walk(root, rel, { recursive, ext }))
    } else if (e.isFile() && (!ext || e.name.endsWith(ext))) {
      out.push(rel)
    }
  }
  return out
}

const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/**
 * Shipped runtime files relative to root, in ASSETS order (without './'):
 * index.html, manifest.webmanifest, then css/, js/ and icons/ files, each group sorted.
 * @returns {Promise<string[]>}
 */
export async function listAssets(root = ROOT) {
  const top = []
  for (const f of TOP_FILES) {
    if (await stat(join(root, f)).then((s) => s.isFile(), () => false)) top.push(f)
  }
  const css = (await walk(root, 'css', { recursive: false, ext: '.css' })).sort(byCodeUnit)
  const js = (await walk(root, 'js', { recursive: true, ext: '.js' })).sort(byCodeUnit)
  const icons = (await walk(root, 'icons', { recursive: false })).sort(byCodeUnit)
  return [...top, ...css, ...js, ...icons]
}

/** First 8 hex chars of the SHA-256 over the sorted paths and their bytes. */
export async function computeVersion(files, root = ROOT) {
  const hash = createHash('sha256')
  for (const f of [...files].sort(byCodeUnit)) {
    hash.update(f)
    hash.update('\0')
    hash.update(await readFile(join(root, f)))
    hash.update('\0')
  }
  return hash.digest('hex').slice(0, 8)
}

const VERSION_RE = /^const VERSION = '[^'\n]*'$/m
const ASSETS_RE = /^const ASSETS = \[[^\]]*\]$/m

/** Reads VERSION and ASSETS back out of sw.js source. */
export function parseSw(source) {
  const v = source.match(/^const VERSION = '([^'\n]*)'$/m)
  const a = source.match(/^const ASSETS = (\[[^\]]*\])$/m)
  if (!v || !a) throw new Error('sw.js: VERSION or ASSETS line not found')
  // The array is generated by this tool: single-quoted strings, one per line, trailing comma.
  const assets = [...a[1].matchAll(/'([^'\n]*)'/g)].map((m) => m[1])
  return { version: v[1], assets }
}

/** sw.js source with VERSION and ASSETS replaced. */
export function renderSw(source, version, files) {
  if (!VERSION_RE.test(source) || !ASSETS_RE.test(source)) throw new Error('sw.js: VERSION or ASSETS line not found')
  const list = ['./', ...files].map((f) => `  '${f}',`).join('\n')
  return source
    .replace(VERSION_RE, () => `const VERSION = '${version}'`)
    .replace(ASSETS_RE, () => `const ASSETS = [\n${list}\n]`)
}

/**
 * Restamps root/sw.js. With check, writes nothing.
 * @returns {Promise<{ version: string, files: string[], changed: boolean }>}
 */
export async function stamp(root = ROOT, { check = false } = {}) {
  const swPath = join(root, 'sw.js')
  const files = await listAssets(root)
  for (const f of files) {
    if (f.includes("'") || f.includes('\n')) throw new Error(`unsupported character in asset path: ${f}`)
  }
  const version = await computeVersion(files, root)
  const source = await readFile(swPath, 'utf8')
  const next = renderSw(source, version, files)
  const changed = next !== source
  if (changed && !check) await writeFile(swPath, next)
  return { version, files, changed }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const { version, files, changed } = await stamp(ROOT, { check })
  if (check) {
    console.log(changed ? `sw.js is stale (expected VERSION ${version})` : `sw.js is up to date (${version})`)
    process.exitCode = changed ? 1 : 0
  } else {
    console.log(`sw.js ${changed ? 'stamped' : 'unchanged'}: VERSION ${version}, ${files.length + 1} assets`)
  }
}
